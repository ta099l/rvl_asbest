"""Build docs/iteration-log.md (Appendix A evidence) from ai/runs/ and ai/prompts/.

    python3 -m ai.james_ai.iteration_log

One section for the rules-only baseline, then one per prompt version: its change
note (ai/prompts/<version>.note.md), the full prompt as sent, a results table of
every saved run, and the wrong and missed cases with reasons. The file is
rebuilt from scratch each time, so it always matches the saved runs; do not
edit it by hand.

Hold-out runs show totals only: their individual lines must not be read, so
they cannot be tuned on.
"""
import json
import sys
from pathlib import Path
from typing import Dict, List, Optional

from .ai_step import PROMPTS_DIR, load_template
from .score import HOLD, OUTCOMES, ROOT, RUNS_DIR

LOG_FILE = ROOT / "docs" / "iteration-log.md"
NOT_RIGHT = ("wrong", "abstained_missed")


def load_runs(runs_dir: Path = RUNS_DIR) -> List[dict]:
    runs = [json.loads(p.read_text(encoding="utf-8")) | {"file": p.name}
            for p in sorted(runs_dir.glob("*.json"))]
    return sorted(runs, key=lambda r: (r.get("run_at", ""), r["file"]))


def prompt_versions(prompts_dir: Path = PROMPTS_DIR) -> List[str]:
    return sorted(p.stem for p in prompts_dir.glob("*.txt") if not p.name.startswith("_"))


def _counts_row(run: dict, variant: str, counts: dict) -> str:
    answered = f"{run['ai_answered']}/{run['lines']}" if "ai_answered" in run else "-"
    return (f"| {run.get('run_at', '?')[:16].replace('T', ' ')} | {run.get('commit') or '?'} | "
            f"{run['set']} | {variant} | {answered} | " + " | ".join(str(counts[k]) for k in OUTCOMES) + " |")


def _table(rows: List[str]) -> List[str]:
    head = "| Run (UTC) | Commit | Set | Variant | AI answers | " + " | ".join(OUTCOMES) + " |"
    return [head, "|" + "---|" * (5 + len(OUTCOMES))] + rows


def _cases(run: dict, variant: Optional[str]) -> List[str]:
    """Wrong links first, then missed ones, each with its reason."""
    out = []
    for kind in NOT_RIGHT:
        for c in run["cases"]:
            got = c[variant] if variant else c
            if got["outcome"] != kind:
                continue
            proposed = got.get("sample", got.get("proposed")) or "no link"
            out.append(f"- **{kind}** {c['id']} [{c['tag']}] `{c.get('line', '')}`: "
                       f"proposed {proposed}, reference {c['truth'] or 'no link'}. "
                       f"Reason: {got['reason'].strip()}")
    return out or ["- none"]


def _run_details(run: dict, variants: List[Optional[str]]) -> List[str]:
    title = f"#### {run['set']} run of {run.get('run_at', '?')[:16].replace('T', ' ')} ({run['file']})"
    if run["set"] == HOLD:
        return [title, "", "Hold-out run: totals only, see the table. Its lines are not shown on purpose.", ""]
    out = [title, ""]
    for v in variants:
        if v:
            out.append(f"*{v}:*")
        out += _cases(run, v) + [""]
    return out


def build(runs_dir: Path = RUNS_DIR, prompts_dir: Path = PROMPTS_DIR) -> str:
    runs = load_runs(runs_dir)
    rules_runs = [r for r in runs if r.get("variant") == "rules"]
    by_prompt: Dict[str, List[dict]] = {}
    for r in runs:
        if r.get("variant") == "compare":
            by_prompt.setdefault(r["prompt"], []).append(r)
    last = runs[-1].get("run_at", "?") if runs else "no runs yet"

    out = ["# Iteration log", "",
           "Generated by `python3 -m ai.james_ai.iteration_log` from `ai/runs/` and `ai/prompts/`. "
           "Do not edit by hand; rebuild it after new runs.", "",
           f"Runs: {len(runs)}. Latest run: {last}. Outcomes: correct, wrong (the one that matters "
           "most), abstained_ok (no link, none existed), abstained_missed (no link, one existed).", "",
           "## Baseline: rules only", ""]
    if rules_runs:
        out += _table([_counts_row(r, "rules", r["counts"]) for r in rules_runs]) + [""]
        for r in rules_runs:
            out += _run_details(r, [None])
    else:
        out += ["No saved runs yet. Save one with `python3 -m ai.james_ai.score --set dev --save`.", ""]

    for v in prompt_versions(prompts_dir):
        note_file = prompts_dir / f"{v}.note.md"
        note = note_file.read_text(encoding="utf-8").strip() if note_file.exists() else "No change note yet."
        out += [f"## Prompt {v}", "", "### Change note", "", note, "",
                "### Full prompt", "", "The register and lab lines are filled in at `{{REGISTER}}` and `{{LINES}}`.",
                "", "```text", load_template(v, prompts_dir).rstrip("\n"), "```", "", "### Results", ""]
        vruns = by_prompt.get(v, [])
        if not vruns:
            out += [f"No saved runs yet. Save one with `python3 -m ai.james_ai.compare --set dev "
                    f"--prompt {v} --replay <file> --save`.", ""]
            continue
        rows = [_counts_row(r, var, r["counts"][var]) for r in vruns for var in ("rules", "ai", "hybrid")]
        out += _table(rows) + ["", "### Wrong and missed cases", ""]
        for r in vruns:
            out += _run_details(r, ["ai", "hybrid"])
    return "\n".join(out).rstrip("\n") + "\n"


def main(argv: Optional[List[str]] = None, runs_dir: Path = RUNS_DIR, prompts_dir: Path = PROMPTS_DIR,
         log_file: Path = LOG_FILE) -> int:
    text = build(runs_dir, prompts_dir)
    log_file.write_text(text, encoding="utf-8")
    print(f"Wrote {log_file} ({len(load_runs(runs_dir))} runs, {len(prompt_versions(prompts_dir))} prompt versions).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
