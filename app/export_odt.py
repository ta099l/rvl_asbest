"""Fill RVL's IHM template (.odt) with the approved results of one lab report.

The template is RVL's property and is not kept in the repository. Its path comes
from the environment variable JAMES_IHM_TEMPLATE, or context/IHM 26-.odt.

How the template works: placeholders such as <projectnumber> sit whole inside the
text (never split by formatting), and tables are never nested. So filling it is
plain text work on content.xml:
- single values are replaced;
- a table row holding placeholders is copied once per item (Part I lists,
  sample tables, lab tables, survey limitations);
- the "Source ... Source Record" heading and its table are copied once per source;
- Table 15 and Table 16 keep their fixed lines and get quantity and unit.
Anything the app does not know is written as "–", so no placeholder is left behind.
"""
import os
import re
import zipfile
from pathlib import Path
from typing import Dict, List, Optional
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_TEMPLATE = ROOT / "context" / "IHM 26-.odt"
DASH = "–"

TABLE = re.compile(r"<table:table [^>]*>.*?</table:table>", re.S)
ROW = re.compile(r"<table:table-row[ >].*?</table:table-row>", re.S)
PLACEHOLDER = re.compile(r"&lt;([a-z_]+)&gt;")


def template_path() -> Path:
    return Path(os.environ.get("JAMES_IHM_TEMPLATE") or DEFAULT_TEMPLATE)


def _fill(xml: str, values: Dict[str, str]) -> str:
    """Replace every placeholder named in values; others stay for a later pass."""
    return PLACEHOLDER.sub(lambda m: escape(str(values[m.group(1)])) if m.group(1) in values else m.group(0), xml)


def _fill_in_order(xml: str, name: str, values: List[str]) -> str:
    """Replace the n-th occurrence of one placeholder with the n-th value (photo grid, fixed lines)."""
    it = iter(values)
    return re.sub(f"&lt;{name}&gt;", lambda m: escape(str(next(it, DASH))), xml)


def repeat_row(table: str, items: List[Dict[str, str]], empty: Dict[str, str]) -> str:
    """Copy the first row that holds placeholders once per item; one 'empty' row when there are none."""
    rows = [m for m in ROW.finditer(table) if PLACEHOLDER.search(m.group(0))]
    if not rows:
        return table
    tpl = rows[0]
    filled = "".join(_fill(tpl.group(0), it) for it in (items or [empty]))
    return table[:tpl.start()] + filled + table[tpl.end():]


def _has(xml: str, *names: str) -> bool:
    return all(f"&lt;{n}&gt;" in xml for n in names)


def build_content(xml: str, report: dict) -> str:
    """Fill content.xml with the report view of the James app (Service.report_view)."""
    ihm = report["ihm"]
    info = dict(ihm["project"])
    v = lambda k: info.get(k) or DASH
    hazardous = sum(len(x) for x in ihm["part1"].values())
    single = {
        "projectnumber": v("Project Number"), "surveylocation": v("Survey Location"), "vesselname": v("Vessel Name"),
        "vessel_name": v("Vessel Name"), "vesseltype": v("Vessel Type"), "clientname": v("Client"),
        "clientaddress": v("Client Address"), "ownername": v("Owner"), "owneraddress": v("Owner Address"),
        "surveyperiod": v("Survey Period"), "surveyor": v("Survey Conducted By"),
        "technicalresponsible": (report["signed"] or {}).get("by") or v("Technical Responsible Person"),
        "projectcoordinator": v("Project Coordinator"), "reportstatus": v("Report Status"),
        "reportversion": v("Report Version"), "validuntil": v("Report Valid Until"),
        "surveyfindings": f" {hazardous} hazardous material(s) above the threshold in approved lab results; "
                          f"{len(ihm['limitations'])} location(s) not sampled (PCHM).",
        "additionalremarks": " Generated by the James prototype from inspector-approved lines only. "
                             + ("" if report["signed"] else "DRAFT: not signed. ") + "Fictitious data.",
    }

    # The 2.3.x sections: each ends with its photo grid ("Foto"). A section starts at the first
    # sample, lab or Source Record table; everything up to and including a photo grid belongs to it.
    tables = list(TABLE.finditer(xml))
    is_photo = ["Foto" in m.group(0) for m in tables]
    is_sec = [_has(m.group(0), "sampleno") or _has(m.group(0), "deck_level") or _has(m.group(0), "certificatenumber")
              or "Source Description" in m.group(0) or is_photo[i] for i, m in enumerate(tables)]
    first = next((i for i, x in enumerate(is_sec) if x), len(tables))
    last = max((i for i, x in enumerate(is_photo) if x), default=-1)
    sections = ihm["sections"][:7]          # 2.3.1 ... 2.3.7, the template's fixed order
    out, pos, k = [], 0, 0
    for i, m in enumerate(tables):
        out.append(xml[pos:m.start()])
        pos = m.end()
        t = m.group(0)
        if first <= i <= last:
            sec = sections[k] if k < len(sections) else {"samples": [], "records": [], "lab": []}
            out.append(_fill_section(t, sec))
            if is_photo[i]:
                k += 1
        else:
            out.append(_fill_table(t, ihm))
    out.append(xml[pos:])
    xml = "".join(out)
    xml = _fill(xml, single)
    return PLACEHOLDER.sub(DASH, xml)        # nothing may stay as a placeholder


def _fill_table(t: str, ihm: dict) -> str:
    q = lambda x: x or "inspector"
    if _has(t, "paintname"):
        items = [{"no": x["no"], "application": x["part"], "paintname": f"{x['material']} ({x['sample']})",
                  "location": x["location"], "materials": x["materials"], "quantity": q(x["quantity"]),
                  "remarks": x["remarks"]} for x in ihm["part1"]["I-1"]]
        return repeat_row(t, items, _none("application"))
    if _has(t, "equipment"):
        items = [{"no": x["no"], "equipment": f"{x['part']} ({x['sample']})", "location": x["location"],
                  "materials": x["materials"], "parts": x["material"], "quantity": q(x["quantity"]),
                  "remarks": x["remarks"]} for x in ihm["part1"]["I-2"]]
        return repeat_row(t, items, _none("equipment"))
    if _has(t, "component"):
        items = [{"no": x["no"], "component": f"{x['part']} ({x['sample']})", "location": x["location"],
                  "materials": x["materials"], "parts": x["material"], "quantity": q(x["quantity"]),
                  "remarks": x["remarks"]} for x in ihm["part1"]["I-3"]]
        return repeat_row(t, items, _none("component"))
    if _has(t, "restriction_number"):
        items = [{"restriction_number": x["no"], "deck_level": x["deck"], "location": f"{x['location']} ({x['sample']}, {x['material']})",
                  "restriction_reason": x["restriction"], "recommended_follow_up": x["follow_up"]} for x in ihm["limitations"]]
        return repeat_row(t, items, {"restriction_number": DASH, "deck_level": DASH,
                                     "location": "No survey restrictions registered", "restriction_reason": DASH,
                                     "recommended_follow_up": DASH})
    if "IHM Table" in t or "Part of IHM" in t:      # Table 15 / Table 16: fixed lines, fill quantity and unit
        return _fill_fixed_lines(t, ihm["table_a"] + ihm["table_b"])
    return t


def _none(first: str) -> dict:
    return {"no": DASH, first: "None identified in approved results", "location": DASH, "materials": DASH,
            "parts": DASH, "quantity": DASH, "remarks": DASH, "paintname": DASH}


# Words that identify each fixed line of Table 15/16 in the template text.
LINE_KEYS = [("A-1", "A-1 Asbestos"), ("A-2", "A-2 Polychlorinated Biphenyls (PCB)"), ("A-3", "A-3 Ozone Depleting Substances (ODS)"),
             ("A-4", "A-4 Anti-fouling Systems Containing Organotin Compounds"), ("B1", "B1 Hexavalent Chromium, B2 Cadmium"),
             ("Batteries", "B3 Lead – Batteries"), ("Paint", "B3 Lead – Paint"), ("HBCDD", "HBCDD"),
             ("Radioactive", "Radioactive Materials"), ("Mercury", "Mercury")]


def _fill_fixed_lines(t: str, lines: List[dict]) -> str:
    by = {x["line"]: x for x in lines}

    def row(m: re.Match) -> str:
        r = m.group(0)
        if not _has(r, "quantity"):
            return r
        text = re.sub(r"<[^>]+>", "", r)
        label = next((lab for key, lab in LINE_KEYS if key in text), None)
        x = by.get(label)
        if not x or not x["found"]:
            return _fill(r, {"quantity": DASH, "unit": DASH})
        if x["quantity"] is None:
            return _fill(r, {"quantity": "to be filled in", "unit": "to be filled in"})
        return _fill(r, {"quantity": x["quantity"], "unit": x["unit"]})
    return ROW.sub(row, t)


def _fill_section(part: str, sec: dict) -> str:
    """One piece (text between tables, or a table) of a 2.3.x section."""
    if part.startswith("<table:table ") and (_has(part, "sampleno") or _has(part, "deck_level")):
        items = [{"sampleno": x["sample"], "sample_number": x["sample"], "decklevel": x["deck"], "deck_level": x["deck"],
                  "location": x["location"], "materialuse": x["material"], "material_use": x["material"],
                  "sampletype": x["type"], "sample_type": x["type"], "analysisresults": x["result"],
                  "analysis_results": x["result"]} for x in sec["samples"]]
        return repeat_row(part, items, {"sampleno": DASH, "sample_number": DASH, "location": "No approved samples in this section"})
    if part.startswith("<table:table ") and _has(part, "certificatenumber"):
        items = [{"samplenumber": x["sample"], "certificatenumber": x["certificate"] or "missing",
                  "analysismethod": x["method"] or DASH, "analysisresult": x["result"], "sampleremarks": x["remarks"] or DASH,
                  "quantity": x["quantity"] or DASH} for x in sec["lab"]]
        return repeat_row(part, items, {"samplenumber": DASH})
    if part.startswith("<table:table ") and "Foto" in part:
        photos = [f"{x['photo'] or 'photo missing'} ({x['sample']})" for x in sec["records"]][:4]
        return _fill_in_order(part, "samplenumber", photos)
    return part                             # Source Records are filled earlier, see _expand_records


def _records(xml_block: str, sec: dict) -> str:
    """Copy 'Source <n> – ... Source Record' heading plus its table once per source."""
    recs = sec["records"] or [{"source": DASH, "description": "No approved samples in this section", "sample": DASH,
                               "certificate": DASH, "location": DASH, "material": DASH, "result": DASH,
                               "quantity": DASH, "conclusion": DASH}]
    out = []
    for r in recs:
        b = _fill(xml_block, {"source_number": f" {r['source']} ", "source_description": r["description"],
                              "sample_number": r["sample"], "laboratory_certificate": r["certificate"] or "missing",
                              "location": r["location"], "material": r["material"], "analysis_results": r["result"],
                              "quantity": r["quantity"] or "inspector"})
        b = b.replace(">This concerns<", ">" + escape(r["conclusion"]) + "<", 1)
        out.append(b)
    return "".join(out)


def _expand_records(xml: str, sections: List[dict]) -> str:
    """Before filling: find each Source Record (heading paragraph + table) and copy it per source."""
    pieces, pos, k = [], 0, 0
    for m in TABLE.finditer(xml):
        t = m.group(0)
        if not _has(t, "source_description"):
            continue
        head = xml.rfind("&lt;source_number&gt;", pos, m.start())
        if head < 0:
            continue
        start = max(xml.rfind("<text:p ", pos, head), xml.rfind("<text:h ", pos, head))
        sec = sections[k] if k < len(sections) else {"records": []}
        k += 1
        pieces.append(xml[pos:start])
        pieces.append(_records(xml[start:m.end()], sec))
        pos = m.end()
    pieces.append(xml[pos:])
    return "".join(pieces)


def export(report: dict, template: Optional[Path] = None) -> bytes:
    """The filled template as .odt bytes. Raises FileNotFoundError when the template is not there."""
    path = Path(template) if template else template_path()
    if not path.is_file():
        raise FileNotFoundError(f"the IHM template was not found at {path}. Put RVL's template there, "
                                f"or set JAMES_IHM_TEMPLATE to its path. It is not kept in the repository.")
    with zipfile.ZipFile(path) as src:
        content = src.read("content.xml").decode("utf-8")
        content = _expand_records(content, report["ihm"]["sections"][:7])
        content = build_content(content, report)
        import io
        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w") as dst:
            # ODF rule: 'mimetype' first and uncompressed, so office programs recognise the file
            dst.writestr(zipfile.ZipInfo("mimetype"), src.read("mimetype"), compress_type=zipfile.ZIP_STORED)
            for item in src.infolist():
                if item.filename == "mimetype":
                    continue
                data = content.encode("utf-8") if item.filename == "content.xml" else src.read(item.filename)
                dst.writestr(item, data, compress_type=zipfile.ZIP_DEFLATED)
    return buf.getvalue()
